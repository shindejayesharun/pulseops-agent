// SSE Streaming / Chat Form Submit
chatForm.addEventListener('submit', async (e) => {
  e.preventDefault();
  const text = chatInput.value.trim();
  if (!text) return;

  appendUserMessage(text);
  chatInput.value = '';

  const assistantMsg = appendAssistantPlaceholder();
  const msgBody = assistantMsg.querySelector('.msg-body');

  try {
    // Attempt Server-Sent Events (SSE) streaming endpoint first
    const res = await fetch('/api/chat/stream', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        conversation_id: conversationId,
        message: text,
        mode: engineSelect.value
      })
    });

    if (!res.ok) {
      throw new Error(`HTTP ${res.status}`);
    }

    const reader = res.body.getReader();
    const decoder = new TextDecoder();
    let buffer = '';

    while (true) {
      const { done, value } = await reader.read();
      if (done) break;

      buffer += decoder.decode(value, { stream: true });
      const lines = buffer.split('\n');
      buffer = lines.pop(); // keep last incomplete line

      for (let i = 0; i < lines.length; i++) {
        const line = lines[i].trim();
        if (line.startsWith('event: ')) {
          const eventType = line.replace('event: ', '');
          const nextDataLine = lines[i + 1] ? lines[i + 1].trim() : '';
          if (nextDataLine.startsWith('data: ')) {
            const dataPayload = JSON.parse(nextDataLine.replace('data: ', ''));
            handleStreamEvent(eventType, dataPayload, msgBody);
            i++; // skip data line
          }
        }
      }
    }

    refreshTraces();

  } catch (err) {
    // Fallback to standard POST /api/chat
    try {
      const fallbackRes = await fetch('/api/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          conversation_id: conversationId,
          message: text,
          mode: engineSelect.value
        })
      });
      const data = await fallbackRes.json();
      msgBody.innerHTML = formatMarkdown(data.response);
      refreshTraces();
    } catch (fallbackErr) {
      msgBody.innerHTML = `<span style="color:var(--accent-red)">Error: ${fallbackErr.message}</span>`;
    }
  }
});

function handleStreamEvent(eventType, data, msgBody) {
  if (eventType === 'tool_start') {
    addLiveTraceCard(data.tool_name, 'running', data.args);
    msgBody.innerHTML = `<em>Calling tool <strong>${data.tool_name}</strong>...</em>`;
  } else if (eventType === 'tool_end') {
    updateLiveTraceCard(data.tool_name, data.ok, data.latency_ms);
  } else if (eventType === 'done') {
    msgBody.innerHTML = formatMarkdown(data.response);
  }
}

function appendUserMessage(text) {
  const div = document.createElement('div');
  div.className = 'message user-msg';
  div.innerHTML = `<div class="msg-body">${formatMarkdown(text)}</div>`;
  chatMessages.appendChild(div);
  chatMessages.scrollTop = chatMessages.scrollHeight;
}

function appendAssistantPlaceholder() {
  const div = document.createElement('div');
  div.className = 'message assistant-msg';
  div.innerHTML = `
    <div class="msg-header">⚡ PulseOps Agent</div>
    <div class="msg-body"><em>Reasoning across internal knowledge...</em></div>
  `;
  chatMessages.appendChild(div);
  chatMessages.scrollTop = chatMessages.scrollHeight;
  return div;
}

function formatMarkdown(text) {
  if (!text) return '';
  return text
    .replace(/\n\n/g, '<br><br>')
    .replace(/\n/g, '<br>')
    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
    .replace(/`(.*?)`/g, '<code style="background:#1e293b;padding:2px 5px;border-radius:4px;color:#38bdf8;">$1</code>');
}

function addLiveTraceCard(toolName, status, args) {
  if (tracesContainer.querySelector('.empty-state')) {
    tracesContainer.innerHTML = '';
  }
  const item = document.createElement('div');
  item.className = 'trace-item';
  item.id = `trace-${toolName}`;
  item.innerHTML = `
    <div class="trace-item-header">
      <span class="trace-tool">🔧 ${toolName}</span>
      <span class="trace-ms">running...</span>
    </div>
    <div style="font-size:11px;color:#94a3b8;">Arguments:</div>
    <pre class="trace-json">${JSON.stringify(args, null, 2)}</pre>
  `;
  tracesContainer.prepend(item);
}

function updateLiveTraceCard(toolName, ok, latency) {
  const item = document.getElementById(`trace-${toolName}`);
  if (item) {
    const msSpan = item.querySelector('.trace-ms');
    if (msSpan) msSpan.textContent = `${latency}ms (${ok ? 'OK' : 'FAIL'})`;
  }
}

async function refreshTraces() {
  try {
    const res = await fetch(`/api/traces/${conversationId}`);
    if (!res.ok) return;
    const data = await res.json();
    traceCountPill.textContent = `${data.count} steps`;

    if (data.traces.length > 0) {
      tracesContainer.innerHTML = data.traces.map((t, idx) => `
        <div class="trace-item">
          <div class="trace-item-header">
            <span class="trace-tool">#${t.step_number} · ${t.tool_name}</span>
            <span class="trace-ms">${t.latency_ms}ms</span>
          </div>
          <div style="font-size:11px;color:#94a3b8;">Input:</div>
          <pre class="trace-json">${JSON.stringify(t.args_json, null, 2)}</pre>
          <div style="font-size:11px;color:#94a3b8;margin-top:4px;">Result:</div>
          <pre class="trace-json">${JSON.stringify(t.result_json, null, 2)}</pre>
        </div>
      `).join('');
    }
  } catch (e) {
    console.error(e);
  }
}

async function loadServices() {
  try {
    const res = await fetch('/api/services');
    if (!res.ok) return;
    const data = await res.json();
    catalogContainer.innerHTML = data.services.map(s => `
      <div class="svc-card">
        <div class="svc-header">
          <span class="svc-name">${s.name}</span>
          <span class="svc-slo">SLO: ${s.slo_availability}%</span>
        </div>
        <p style="font-size:12px;color:#cbd5e1;">${s.description}</p>
        <div class="svc-meta">
          <div>Team: <strong style="color:#fff">${s.team}</strong></div>
          <div>On-Call: <code style="color:#38bdf8">${s.oncall}</code></div>
          <div>Repo: <span style="font-family:var(--font-mono)">${s.repo}</span></div>
        </div>
        <div class="svc-deps">
          ${s.depends_on.map(d => `<span class="dep-tag">${d}</span>`).join('')}
        </div>
      </div>
    `).join('');
  } catch (e) {
    catalogContainer.innerHTML = '<div class="empty-state">Failed to load services catalog.</div>';
  }
}

async function loadTickets() {
  try {
    const res = await fetch('/api/tickets/all');
    if (!res.ok) return;
    const data = await res.json();
    ticketBadge.textContent = data.count;

    ticketsContainer.innerHTML = data.tickets.map(t => `
      <div class="ticket-card">
        <div style="display:flex;justify-content:space-between;align-items:center;margin-bottom:8px;">
          <strong style="color:var(--accent-amber)">${t.id}</strong>
          <span class="dep-tag" style="background:#3b82f6;color:#fff">${t.severity || 'P3'}</span>
        </div>
        <div style="font-weight:600;font-size:13px;margin-bottom:6px;">${t.title}</div>
        <div style="font-size:11px;color:#94a3b8;">
          Team: <strong>${t.team}</strong> · Status: <em>${t.status}</em> · ${t.is_draft ? '<span style="color:var(--accent-amber)">[Local Draft]</span>' : '<span style="color:var(--accent-green)">[Incident Record]</span>'}
        </div>
      </div>
    `).join('');
  } catch (e) {
    ticketsContainer.innerHTML = '<div class="empty-state">Failed to load tickets.</div>';
  }
}

async function loadPRs() {
  try {
    const [prsRes, sumsRes] = await Promise.all([
      fetch('/api/prs'),
      fetch('/api/prs/summaries')
    ]);
    const prData = await prsRes.json();
    const sumData = await sumsRes.json();

    const summariesMap = {};
    (sumData.summaries || []).forEach(s => summariesMap[s.pr_number] = s);

    prsContainer.innerHTML = prData.prs.map(p => {
      const sumRecord = summariesMap[p.number];
      return `
        <div class="pr-card">
          <div style="display:flex;justify-content:space-between;align-items:center;margin-bottom:6px;">
            <strong style="color:var(--accent-purple)">PR #${p.number}</strong>
            <span class="dep-tag" style="background:#1e293b;color:var(--accent-green)">Risk: ${sumRecord ? sumRecord.risk_level : p.risk_level}</span>
          </div>
          <div style="font-size:13px;font-weight:600;margin-bottom:6px;">${p.title}</div>
          <p style="font-size:12px;color:#cbd5e1;margin-bottom:8px;">${p.description}</p>
          <div style="font-size:11px;color:#94a3b8;">
            Author: <code>@${p.author}</code> · Files: ${p.files_changed ? p.files_changed.length : 'N/A'}
          </div>
          ${sumRecord ? `
            <div style="margin-top:8px;padding-top:8px;border-top:1px solid #334155;font-size:11px;color:#7dd3fc;">
              <strong>Persisted Notes:</strong> ${sumRecord.risk_notes}
            </div>
          ` : ''}
        </div>
      `;
    }).join('');
  } catch (e) {
    prsContainer.innerHTML = '<div class="empty-state">Failed to load pull requests.</div>';
  }
}

